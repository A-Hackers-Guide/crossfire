//! Stub backends for OS-specific source files.
//!
//! When a translation unit is tied to one OS (e.g. an X11 window backend) it is
//! compiled only there; on the other targets Crossfire compiles a generated
//! stub with the same top-level function signatures so the project still
//! links and runs, with a runtime warning. The stubs are the place to write
//! (or let the AI write) the real port.

use regex::Regex;
use std::sync::LazyLock;

#[derive(Debug, Clone, PartialEq)]
pub struct FnSig {
    pub ret: String,
    pub name: String,
    pub params: String,
}

/// Remove comments and string/char literal contents (keeps line structure).
pub fn strip_comments(src: &str) -> String {
    let b = src.as_bytes();
    let mut out = String::with_capacity(src.len());
    let mut i = 0;
    while i < b.len() {
        let c = b[i] as char;
        if c == '/' && i + 1 < b.len() && b[i + 1] == b'/' {
            while i < b.len() && b[i] != b'\n' {
                i += 1;
            }
        } else if c == '/' && i + 1 < b.len() && b[i + 1] == b'*' {
            i += 2;
            while i + 1 < b.len() && !(b[i] == b'*' && b[i + 1] == b'/') {
                if b[i] == b'\n' {
                    out.push('\n');
                }
                i += 1;
            }
            i += 2;
        } else if c == '"' || c == '\'' {
            out.push(c);
            i += 1;
            while i < b.len() && b[i] as char != c && b[i] != b'\n' {
                if b[i] == b'\\' {
                    i += 1;
                }
                i += 1;
            }
            out.push(c);
            i += 1;
        } else {
            // Copy one UTF-8 char.
            let ch = src[i..].chars().next().unwrap_or(' ');
            out.push(ch);
            i += ch.len_utf8();
        }
    }
    out
}

const NOT_FUNCS: &[&str] = &["if", "for", "while", "switch", "return", "else", "do", "sizeof", "case", "catch"];

/// Top-level, non-static function definitions (column-0 heuristics).
pub fn function_definitions(src: &str) -> Vec<FnSig> {
    static DEF: LazyLock<Regex> = LazyLock::new(|| {
        Regex::new(r"(?m)^([A-Za-z_][\w:<>,\*&\s]*?[\s\*&])([A-Za-z_][\w:~]*)\s*\(([^;{}()]*(?:\([^()]*\)[^;{}()]*)*)\)\s*(?:const\s*)?(?:noexcept\s*)?\{").unwrap()
    });
    let clean = strip_comments(src);
    // Drop preprocessor lines so `#define F(x) {` is not mistaken for a function.
    let clean: String = clean
        .lines()
        .map(|l| if l.trim_start().starts_with('#') { "" } else { l })
        .collect::<Vec<_>>()
        .join("\n");
    let mut v = Vec::new();
    for c in DEF.captures_iter(&clean) {
        let ret = c[1].split_whitespace().collect::<Vec<_>>().join(" ");
        let name = c[2].to_string();
        let first = ret.split_whitespace().next().unwrap_or("");
        if ret.is_empty()
            || NOT_FUNCS.contains(&first)
            || NOT_FUNCS.contains(&name.as_str())
            || ret.split_whitespace().any(|w| matches!(w, "static" | "typedef" | "inline" | "constexpr"))
            || ret.contains("inline")
        {
            continue;
        }
        let params = c[3].split_whitespace().collect::<Vec<_>>().join(" ");
        if !v.iter().any(|s: &FnSig| s.name == name && s.params == params) {
            v.push(FnSig { ret, name, params });
        }
    }
    v
}

fn is_entry(name: &str) -> bool {
    matches!(name, "main" | "WinMain" | "wWinMain" | "_tWinMain")
}

/// Strip calling-convention / linkage words so the type can declare a local.
fn value_type(ret: &str) -> String {
    ret.split_whitespace()
        .filter(|w| !matches!(*w, "WINAPI" | "CALLBACK" | "APIENTRY" | "__stdcall" | "__cdecl" | "extern" | "\"C\"" | "CF_EXPORT" | "CF_IMPORT" | "virtual"))
        .collect::<Vec<_>>()
        .join(" ")
}

/// Generate a stub translation unit for `rel` (original source text `src`).
/// `includes` are project-root-relative header paths to include.
pub fn generate_stub(rel: &str, src: &str, cpp: bool, includes: &[String], os_label: &str) -> (String, Vec<String>) {
    let sigs = function_definitions(src);
    let mut s = String::new();
    s.push_str(&format!(
        "/* Generated by Crossfire: stub for {rel} on platforms without {os_label}.\n * {rel} uses OS-specific APIs and is only compiled on {os_label}.\n * Implement these functions with the chosen portable APIs (or run the AI pass).\n */\n"
    ));
    s.push_str("#include \"crossfire/cf_platform.h\"\n");
    if !cpp {
        s.push_str("#include <string.h>\n");
    }
    for inc in includes {
        s.push_str(&format!("#include \"{inc}\"\n"));
    }
    s.push('\n');
    let mut names = Vec::new();
    for f in &sigs {
        names.push(f.name.clone());
        if is_entry(&f.name) {
            s.push_str(&format!(
                "int main(int argc, char **argv) {{\n    (void)argc; (void)argv;\n    cf_stub_warn(\"{}\", \"{rel}\");\n    fprintf(stderr, \"{rel} is only implemented for {os_label}; port it for this OS.\\n\");\n    return 1;\n}}\n\n",
                f.name
            ));
            continue;
        }
        let vt = value_type(&f.ret);
        let body = if vt == "void" {
            String::new()
        } else if cpp {
            "    return {};\n".to_string()
        } else if vt.ends_with('*') {
            "    return NULL;\n".to_string()
        } else {
            format!("    {vt} cf_r;\n    memset(&cf_r, 0, sizeof cf_r);\n    return cf_r;\n")
        };
        s.push_str(&format!("{} {}({}) {{\n    cf_stub_warn(\"{}\", \"{rel}\");\n{body}}}\n\n", f.ret, f.name, f.params, f.name));
    }
    (s, names)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn finds_top_level_functions() {
        let src = "#include <X11/Xlib.h>\nstatic Display *dpy;\n/* int fake(void) { */\nint window_open(int w, int h, const char *title)\n{\n  if (x) { }\n  return 0;\n}\nstatic void helper(void) {}\nvoid window_close(void) {\n}\nint main(int argc, char **argv) { return 0; }\n";
        let f = function_definitions(src);
        let names: Vec<&str> = f.iter().map(|x| x.name.as_str()).collect();
        assert_eq!(names, vec!["window_open", "window_close", "main"]);
        assert_eq!(f[0].params, "int w, int h, const char *title");
    }

    #[test]
    fn stub_compiles_shape() {
        let (s, names) = generate_stub("src/a.c", "float audio_level(void) { return 1; }\nchar *name(void) { return 0; }\n", false, &["src/a.h".into()], "Linux");
        assert_eq!(names, vec!["audio_level", "name"]);
        assert!(s.contains("float cf_r;"));
        assert!(s.contains("return NULL;"));
        assert!(s.contains("#include \"src/a.h\""));
    }

    #[test]
    fn cpp_methods_and_winmain() {
        let src = "LRESULT CALLBACK WndProc(HWND h, UINT m, WPARAM w, LPARAM l) { return 0; }\nint WINAPI WinMain(HINSTANCE a, HINSTANCE b, LPSTR c, int d) { return 0; }\nbool Renderer::init(int w) { return true; }\n";
        let (s, names) = generate_stub("main.cpp", src, true, &[], "Windows");
        assert_eq!(names, vec!["WndProc", "WinMain", "Renderer::init"]);
        assert!(s.contains("int main(int argc, char **argv)"));
        assert!(s.contains("bool Renderer::init(int w) {"));
    }
}
